et_RET App_Init(void){
  
  RET_REGISTER(ret);

  ret = FSM_Initialize();
  if(CHECK_RET_ERROR(ret))
  {
    PRINT_E("[APP] error initializing App. ");
    return -RET_NOT_OK;
  }

  return RET_OK;
}

et_RET App_Loop(void)
{
  RET_REGISTER(ret);

  ret = FSM_EncodeFSM();

  if(CHECK_RET_ERROR(ret))
  {
    PRINT_E("[APP] error looping app. ");
    return -RET_NOT_OK;
  }

  return RET_OK;
}


